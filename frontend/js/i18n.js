  const STORAGE_KEY = "cropai.lang";
  let current = "ru";
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "ru" || saved === "en") current = saved; // Russian by default (thesis language)
  } catch (e) { /* storage unavailable */ }

  function t(key, vars) {
    let s = (dict[current] && dict[current][key]) || dict.en[key] || key;
    if (vars) Object.keys(vars).forEach((k) => { s = s.replace(new RegExp("\\{" + k + "\\}", "g"), vars[k]); });
    return s;
  }

  function apply(root) {
    (root || document).querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.getAttribute("data-i18n")); });
    (root || document).querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder"))); });
    (root || document).querySelectorAll("[data-i18n-title]").forEach((el) => { el.setAttribute("title", t(el.getAttribute("data-i18n-title"))); el.setAttribute("aria-label", t(el.getAttribute("data-i18n-title"))); });
    document.documentElement.lang = current;
    document.querySelectorAll(".lang-switch button").forEach((b) => b.setAttribute("aria-pressed", String(b.dataset.lang === current)));
  }

  function setLang(lang) {
    if (lang !== "ru" && lang !== "en") return;
    current = lang;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) { /* ignore */ }
    apply();
    document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
  }

  window.i18n = { t, apply, setLang, get lang() { return current; } };
  window.t = t;
